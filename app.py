def _create_cookie_file(cookies_list):
    if not cookies_list:
        return None
    
    temp_fd, path = tempfile.mkstemp(suffix='.txt')
    try:
        with os.fdopen(temp_fd, 'w', encoding='utf-8') as f:
            f.write("# Netscape HTTP Cookie File\n")
            f.write("# This file is generated by TakeVid\n")
            for c in cookies_list:
                domain = c.get('domain', '')
                if not domain:
                    continue
                
                flag = "TRUE" if domain.startswith('.') else "FALSE"
                path_str = c.get('path', '/')
                secure = "TRUE" if c.get('secure', False) else "FALSE"
                expiry = int(c.get('expirationDate', time.time() + 86400))
                name = c.get('name', '')
                value = c.get('value', '')
                
                f.write(f"{domain}\t{flag}\t{path_str}\t{secure}\t{expiry}\t{name}\t{value}\n")
        return path
    except (IOError, OSError) as e:
        print(f"Error creating cookie file: {e}")
        try:
            os.close(temp_fd)
        except OSError:
            pass
        return None

def _cleanup_temp_files(base_name, cookie_path=None):
    """Clean up all temp files matching the base name, including subtitle files."""
    try:
        for file in os.listdir('.'):
            if file.startswith(base_name):
                try:
                    os.remove(file)
                except OSError:
                    pass
        if cookie_path and os.path.exists(cookie_path):
            try:
                os.remove(cookie_path)
            except OSError:
                pass
    except OSError:
        pass

